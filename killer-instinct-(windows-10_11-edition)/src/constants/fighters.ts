export function getComboTier(hits: number): string {
  if (hits < 3) return '';
  for (let i = COMBO_TIERS.length - 1; i >= 0; i--) {
    if (hits >= COMBO_TIERS[i].minHits) {
      return COMBO_TIERS[i].name;
    }
  }
  return 'COMBO';
}
